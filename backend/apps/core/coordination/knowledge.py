"""Vehicle-private knowledge store for local observations, reports, and belief states."""

from typing import Any, Optional

from apps.core.coordination.exceptions import (
    CoordinationStateError,
    DuplicateReportError,
    ExpiredReportError,
    InvalidReportError,
)
from apps.core.coordination.fusion import (
    InformationFusion,
    derive_belief_id,
)
from apps.core.coordination.models import (
    BeliefRecord,
    BeliefStatus,
    CoordinationConfig,
    KnowledgeStoreSnapshot,
    ReportType,
    TrafficReport,
)


class VehicleKnowledgeStore:
    """Isolated, vehicle-private store of traffic reports and interpreted belief states.

    Attributes:
        vehicle_id: Unique identifier of the vehicle owning this store.
        config: Subsystem coordination configuration.
    """

    def __init__(self, vehicle_id: str, config: Optional[CoordinationConfig] = None) -> None:
        if not isinstance(vehicle_id, str) or not vehicle_id.strip():
            raise InvalidReportError("vehicle_id must be a non-empty string.", field="vehicle_id")

        self.vehicle_id: str = vehicle_id
        self.config: CoordinationConfig = config or CoordinationConfig()

        self._reports: dict[str, TrafficReport] = {}
        self._edge_index: dict[str, set[str]] = {}
        self._type_index: dict[ReportType, set[str]] = {t: set() for t in ReportType}
        self._seen_report_ids: set[str] = set()
        self._forwarded_report_ids: set[str] = set()
        self._beliefs: dict[str, BeliefRecord] = {}

    @property
    def report_count(self) -> int:
        """Total number of reports currently retained in this vehicle's store."""
        return len(self._reports)

    @property
    def belief_count(self) -> int:
        """Total number of beliefs tracked in this store."""
        return len(self._beliefs)

    def add_observation(
        self,
        report: TrafficReport,
        current_time_s: float = 0.0,
    ) -> bool:
        """Record a locally observed traffic event directly generated by this vehicle.

        Args:
            report: Validated traffic report created by this vehicle.
            current_time_s: Current authoritative simulation time.

        Returns:
            True if observation was successfully added and fused into beliefs.

        Raises:
            ExpiredReportError: If report is already expired.
            DuplicateReportError: If report ID already exists in store.
        """
        if report.is_expired(current_time_s):
            raise ExpiredReportError(
                report_id=report.report_id,
                expiry_timestamp_s=report.expiry_timestamp_s or 0.0,
                current_time_s=current_time_s,
            )

        if report.report_id in self._seen_report_ids:
            raise DuplicateReportError(report.report_id)

        self._store_report(report)
        self._update_belief(report, current_time_s)
        return True

    def ingest_report(
        self,
        report: TrafficReport,
        current_time_s: float,
    ) -> bool:
        """Ingest and fuse a traffic report received from the V2V communication network.

        Performs validation against configuration, category filters, expiration,
        trust threshold, and deduplication.

        Args:
            report: Received traffic report.
            current_time_s: Current simulation timestamp.

        Returns:
            True if report was accepted and fused; False if rejected or duplicate.
        """
        if not self.config.enabled:
            return False

        if report.report_type not in self.config.enabled_categories:
            return False

        if report.confidence < self.config.trust_threshold:
            return False

        if report.report_id in self._seen_report_ids:
            return False

        if report.is_expired(current_time_s):
            return False

        # Enforce max cache size by purging oldest expired or lowest timestamp entries if full
        if len(self._reports) >= self.config.max_cache_size:
            self._evict_oldest_report(current_time_s)

        self._store_report(report)
        self._update_belief(report, current_time_s)
        return True

    def get_report(self, report_id: str) -> Optional[TrafficReport]:
        """Retrieve a stored traffic report by its unique report ID."""
        return self._reports.get(report_id)

    def query_reports(
        self,
        edge_id: Optional[str] = None,
        report_type: Optional[ReportType] = None,
        active_only: bool = True,
        current_time_s: float = 0.0,
    ) -> list[TrafficReport]:
        """Query stored reports with optional filters in deterministic sorted order.

        Args:
            edge_id: Optional road-edge identifier filter.
            report_type: Optional report category filter.
            active_only: If True, exclude reports that are currently expired.
            current_time_s: Current simulation timestamp for expiration check.

        Returns:
            List of matching TrafficReport instances sorted deterministically by
            (-timestamp_s, report_id).
        """
        candidate_ids: Optional[set[str]] = None

        if edge_id is not None:
            candidate_ids = set(self._edge_index.get(edge_id, set()))

        if report_type is not None:
            type_ids = self._type_index.get(report_type, set())
            if candidate_ids is None:
                candidate_ids = set(type_ids)
            else:
                candidate_ids &= type_ids

        if candidate_ids is None:
            candidates = list(self._reports.values())
        else:
            candidates = [self._reports[rid] for rid in candidate_ids if rid in self._reports]

        if active_only:
            candidates = [r for r in candidates if not r.is_expired(current_time_s)]

        # Deterministic sorting: most recent simulation time first, then lexicographical report_id
        candidates.sort(key=lambda r: (-r.timestamp_s, r.report_id))
        return candidates

    def get_belief(self, belief_id: str) -> Optional[BeliefRecord]:
        """Retrieve an interpreted belief record by belief ID."""
        return self._beliefs.get(belief_id)

    def get_beliefs(
        self,
        active_only: bool = True,
        current_time_s: float = 0.0,
    ) -> dict[str, BeliefRecord]:
        """Retrieve beliefs in deterministic sorted dictionary order.

        Args:
            active_only: If True, exclude beliefs that are expired.
            current_time_s: Current simulation timestamp.

        Returns:
            Dictionary mapping belief_id to BeliefRecord sorted alphabetically by key.
        """
        result: dict[str, BeliefRecord] = {}
        for bid in sorted(self._beliefs.keys()):
            belief = self._beliefs[bid]
            if active_only and (
                belief.is_expired(current_time_s) or belief.status == BeliefStatus.EXPIRED
            ):
                continue
            result[bid] = belief
        return result

    def query_beliefs_for_edge(
        self,
        edge_id: str,
        active_only: bool = True,
        current_time_s: float = 0.0,
    ) -> list[BeliefRecord]:
        """Retrieve all active beliefs associated with a specific road edge.

        Args:
            edge_id: Road network edge identifier.
            active_only: If True, exclude expired beliefs.
            current_time_s: Current simulation timestamp.

        Returns:
            List of matching BeliefRecords sorted by belief_id.
        """
        matched: list[BeliefRecord] = []
        for bid in sorted(self._beliefs.keys()):
            belief = self._beliefs[bid]
            if belief.target_id == edge_id:
                if active_only and (
                    belief.is_expired(current_time_s) or belief.status == BeliefStatus.EXPIRED
                ):
                    continue
                matched.append(belief)
        return matched

    def expire_entries(self, current_time_s: float) -> tuple[int, int]:
        """Scan and transition expired reports and beliefs.

        Args:
            current_time_s: Current authoritative simulation time.

        Returns:
            Tuple of (reports_expired_count, beliefs_expired_count).
        """
        reports_expired = 0
        for r in self._reports.values():
            if r.is_expired(current_time_s):
                reports_expired += 1

        beliefs_expired = 0
        updated_beliefs: dict[str, BeliefRecord] = {}
        for bid, belief in self._beliefs.items():
            if belief.status != BeliefStatus.EXPIRED and belief.is_expired(current_time_s):
                updated_beliefs[bid] = BeliefRecord(
                    belief_id=belief.belief_id,
                    belief_type=belief.belief_type,
                    target_id=belief.target_id,
                    status=BeliefStatus.EXPIRED,
                    confidence=belief.confidence,
                    last_evidence_timestamp_s=belief.last_evidence_timestamp_s,
                    expiry_timestamp_s=belief.expiry_timestamp_s,
                    evidence_report_ids=belief.evidence_report_ids,
                    evidence_sources=belief.evidence_sources,
                    attributes=dict(belief.attributes),
                    dispute_reason="Report validity window expired.",
                )
                beliefs_expired += 1
            else:
                updated_beliefs[bid] = belief

        self._beliefs = updated_beliefs
        return reports_expired, beliefs_expired

    def has_seen_report(self, report_id: str) -> bool:
        """Check if this vehicle has ever ingested or observed this report ID."""
        return report_id in self._seen_report_ids

    def has_forwarded_report(self, report_id: str) -> bool:
        """Check if this vehicle has already relayed this report ID to neighbors."""
        return report_id in self._forwarded_report_ids

    def mark_report_forwarded(self, report_id: str) -> None:
        """Record that this vehicle forwarded the report to prevent rebroadcast loops."""
        self._forwarded_report_ids.add(report_id)

    def capture_state(self) -> dict[str, Any]:
        """Capture an isolated, deep snapshot of this store for atomic rollback."""
        return {
            "vehicle_id": self.vehicle_id,
            "reports": dict(self._reports),
            "edge_index": {k: set(v) for k, v in self._edge_index.items()},
            "type_index": {k: set(v) for k, v in self._type_index.items()},
            "seen_report_ids": set(self._seen_report_ids),
            "forwarded_report_ids": set(self._forwarded_report_ids),
            "beliefs": dict(self._beliefs),
        }

    def restore_state(self, state: dict[str, Any]) -> None:
        """Restore internal state from a previously captured rollback snapshot.

        Args:
            state: Dictionary produced by capture_state().

        Raises:
            CoordinationStateError: If snapshot is invalid or belongs to another vehicle.
        """
        if not isinstance(state, dict):
            raise CoordinationStateError("Rollback state must be a dictionary.")
        if state.get("vehicle_id") != self.vehicle_id:
            raise CoordinationStateError(
                f"Cannot restore state: vehicle_id mismatch "
                f"({state.get('vehicle_id')} != {self.vehicle_id})."
            )

        try:
            self._reports = dict(state["reports"])
            self._edge_index = {k: set(v) for k, v in state["edge_index"].items()}
            self._type_index = {k: set(v) for k, v in state["type_index"].items()}
            self._seen_report_ids = set(state["seen_report_ids"])
            self._forwarded_report_ids = set(state["forwarded_report_ids"])
            self._beliefs = dict(state["beliefs"])
        except Exception as exc:
            raise CoordinationStateError(f"Failed to restore knowledge store state: {exc}") from exc

    def get_snapshot(self, current_time_s: float = 0.0) -> KnowledgeStoreSnapshot:
        """Generate an immutable point-in-time snapshot of this private knowledge store."""
        active_reports = sum(1 for r in self._reports.values() if not r.is_expired(current_time_s))
        active_beliefs = sum(
            1
            for b in self._beliefs.values()
            if not b.is_expired(current_time_s) and b.status != BeliefStatus.EXPIRED
        )

        return KnowledgeStoreSnapshot(
            vehicle_id=self.vehicle_id,
            report_count=len(self._reports),
            active_report_count=active_reports,
            belief_count=len(self._beliefs),
            active_belief_count=active_beliefs,
            reports={rid: r.to_dict() for rid, r in sorted(self._reports.items())},
            beliefs={bid: b.to_dict() for bid, b in sorted(self._beliefs.items())},
        )

    def _store_report(self, report: TrafficReport) -> None:
        """Internal helper to store a report and update indexing structures."""
        self._reports[report.report_id] = report
        self._seen_report_ids.add(report.report_id)

        edge_id = getattr(report, "edge_id", None)
        if edge_id:
            if edge_id not in self._edge_index:
                self._edge_index[edge_id] = set()
            self._edge_index[edge_id].add(report.report_id)

        if report.report_type in self._type_index:
            self._type_index[report.report_type].add(report.report_id)

    def _update_belief(self, report: TrafficReport, current_time_s: float) -> None:
        """Internal helper to update or create belief state from a valid report."""
        belief_id = derive_belief_id(report)
        existing = self._beliefs.get(belief_id)

        updated_belief, _, _ = InformationFusion.fuse_single_report(
            existing_belief=existing,
            new_report=report,
            current_time_s=current_time_s,
            config=self.config,
        )
        self._beliefs[belief_id] = updated_belief

    def _evict_oldest_report(self, current_time_s: float) -> None:
        """Evict expired or oldest report when cache limit is reached."""
        # First try finding an expired report
        for rid, r in list(self._reports.items()):
            if r.is_expired(current_time_s):
                self._remove_report(rid)
                return

        # Otherwise evict report with oldest timestamp
        oldest_rid = min(self._reports.keys(), key=lambda rid: self._reports[rid].timestamp_s)
        self._remove_report(oldest_rid)

    def _remove_report(self, report_id: str) -> None:
        """Remove a report and clean indexes."""
        if report_id not in self._reports:
            return
        report = self._reports.pop(report_id)
        edge_id = getattr(report, "edge_id", None)
        if edge_id and edge_id in self._edge_index:
            self._edge_index[edge_id].discard(report_id)
        if report.report_type in self._type_index:
            self._type_index[report.report_type].discard(report_id)
